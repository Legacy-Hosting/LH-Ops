#!/usr/bin/env node

import {
  chmodSync,
  existsSync,
  lstatSync,
  readFileSync,
  statSync,
  unlinkSync,
  writeFileSync,
} from "node:fs";
import { resolve } from "node:path";

if (process.getuid?.() !== 0 || process.argv.length !== 5) {
  console.error("Usage as root: activate-migrated-api-environment.mjs LEGACY_API_ENV SSO_FRAGMENT OUTPUT_ENV");
  process.exit(2);
}

const legacyEnvironment = resolve(process.argv[2]);
const ssoFragment = resolve(process.argv[3]);
const output = resolve(process.argv[4]);
for (const input of [legacyEnvironment, ssoFragment]) {
  if (!existsSync(input) || lstatSync(input).isSymbolicLink() || !lstatSync(input).isFile()) {
    throw new Error(`Protected input must be a regular file: ${input}`);
  }
  if ((statSync(input).mode & 0o077) !== 0) {
    throw new Error(`Protected input must have mode 0600 or stricter: ${input}`);
  }
}
if (existsSync(output)) throw new Error(`Refusing to overwrite API environment: ${output}`);

function parseKeys(contents, source) {
  const keys = new Set();
  for (const rawLine of contents.split(/\r?\n/u)) {
    if (!rawLine || rawLine.startsWith("#")) continue;
    const match = /^([A-Z][A-Z0-9_]*)=(.*)$/u.exec(rawLine);
    if (!match || keys.has(match[1])) throw new Error(`Invalid or duplicate setting in ${source}.`);
    keys.add(match[1]);
  }
  return keys;
}

const legacyContents = readFileSync(legacyEnvironment, "utf8");
const fragmentContents = readFileSync(ssoFragment, "utf8").trimEnd();
const legacyKeys = parseKeys(legacyContents, legacyEnvironment);
const fragmentKeys = parseKeys(fragmentContents, ssoFragment);
const expectedFragmentKeys = new Set([
  "SSO_INTERNAL_URL",
  "SSO_ISSUER",
  "SSO_JWKS_URL",
  "HUB_SSO_AUDIENCE",
  "SSO_IDENTITY_BRIDGE_TOKEN",
  "SSO_CLIENT_ID",
  "SSO_CLIENT_SECRET",
  "SSO_REDIRECT_URI",
  "SSO_RESOURCE",
  "SSO_REQUEST_TIMEOUT_MS",
]);
if (
  fragmentKeys.size !== expectedFragmentKeys.size ||
  [...expectedFragmentKeys].some((key) => !fragmentKeys.has(key))
) {
  throw new Error("SSO fragment does not contain the expected API settings.");
}
for (const key of expectedFragmentKeys) {
  if (legacyKeys.has(key)) throw new Error(`Legacy API environment already defines ${key}.`);
}
if (legacyKeys.has("AGENT_DISTRIBUTION_DIRECTORY")) {
  throw new Error("Legacy API environment already defines AGENT_DISTRIBUTION_DIRECTORY.");
}
if (!legacyKeys.has("DATABASE_SSL_CA")) {
  throw new Error("Legacy API environment is missing DATABASE_SSL_CA.");
}

const migratedLines = legacyContents.split(/\r?\n/u).map((line) =>
  line.startsWith("DATABASE_SSL_CA=")
    ? "DATABASE_SSL_CA=/etc/legacy-hosting/database-ca.pem"
    : line,
);
while (migratedLines.at(-1) === "") migratedLines.pop();
migratedLines.push(
  "",
  "# Split-service identity configuration generated by LH-Ops.",
  "AGENT_DISTRIBUTION_DIRECTORY=/var/lib/legacy-hosting/agent-distributions/current",
  fragmentContents,
  "",
);

writeFileSync(output, migratedLines.join("\n"), {
  encoding: "utf8",
  flag: "wx",
  mode: 0o600,
});
chmodSync(output, 0o600);
unlinkSync(ssoFragment);
console.log(`Activated protected migrated API environment: ${output}`);
